import assert from 'node:assert/strict'
import fs from 'node:fs'
import path from 'node:path'
import { chromium } from 'playwright-core'
import { routes, getSeo, siteUrl } from '../src/seo/site.js'
import { company } from '../src/data/company.js'
const base = process.env.SEO_TEST_URL || 'http://127.0.0.1:4173'
const out = 'docs/seo-evidence'
fs.mkdirSync(out,{recursive:true})
const chrome = process.env.SCROLLCRAFT_CHROME || 'C:/Program Files/Google/Chrome/Application/chrome.exe'
const browser = await chromium.launch({executablePath:chrome,headless:true})
const noJs = await browser.newContext({javaScriptEnabled:false,viewport:{width:1440,height:900}})
const page = await noJs.newPage()
const report = { pages:[], hydrationErrors:[], navigation:[], checks:[] }
const titleSet = new Set(), descriptionSet = new Set()
try {
  const sitemap = fs.readFileSync('dist/sitemap.xml','utf8')
  const sitemapUrls = [...sitemap.matchAll(/<loc>([^<]+)<\/loc>/g)].map(match=>match[1])
  assert.equal(new Set(sitemapUrls).size,routes.length)
  assert.deepEqual(new Set(sitemapUrls),new Set(routes.map(route=>siteUrl+route.path)))
  assert(fs.readFileSync('dist/robots.txt','utf8').includes(`Sitemap: ${siteUrl}/sitemap.xml`))
  for (const route of routes) {
    const response = await page.goto(base+route.path,{waitUntil:'networkidle'})
    assert.equal(response.status(),200,route.path)
    const raw = await response.text()
    assert(raw.includes('data-prerendered="true"'),route.path+' has static body')
    assert(!/your-verification|your-facebook|SearchAction/.test(raw))
    assert.equal(await page.locator('h1').count(),1,route.path+' one h1')
    assert.equal(await page.locator('title').count(),1)
    assert.equal(await page.title(),route.title)
    assert.equal(await page.locator('meta[name="description"]').count(),1)
    assert.equal(await page.locator('meta[name="description"]').getAttribute('content'),route.description)
    assert.equal(await page.locator('link[rel="canonical"]').count(),1)
    assert.equal(await page.locator('link[rel="canonical"]').getAttribute('href'),siteUrl+route.path)
    assert.equal(await page.locator('meta[property="og:url"]').getAttribute('content'),siteUrl+route.path)
    const structured = JSON.parse(await page.locator('#seo-structured-data').textContent())
    assert(structured['@graph'].some(node=>node['@type']==='Organization'))
    const organization = structured['@graph'].find(node=>node['@type']==='Organization')
    assert.equal(organization.email,company.email)
    assert.equal(organization.telephone,company.phone)
    if (route.article) {
      const article = structured['@graph'].find(node=>node['@type']==='BlogPosting')
      assert(article,route.path+' has BlogPosting schema')
      assert.equal(article.headline,route.article.title)
      assert.equal(article.inLanguage,'en-US')
      assert.equal(await page.locator('meta[property="og:type"]').getAttribute('content'),'article')
      const crumbs=structured['@graph'].find(node=>node['@type']==='BreadcrumbList')
      assert.deepEqual(crumbs.itemListElement.map(item=>item.name),['Home','Blog',route.article.title])
    }

    assert.equal(structured['@graph'].some(node=>node['@type']==='Service'),route.path.startsWith('/services/'))
    const links = await page.locator('a[href^="/"]').evaluateAll(items=>items.map(item=>item.getAttribute('href').split('#')[0].split('?')[0]))
    for (const href of links) assert(routes.some(item=>item.path===href),route.path+' broken internal link '+href)
    assert.equal(await page.locator('img:not([alt])').count(),0)
    titleSet.add(route.title); descriptionSet.add(route.description)
    report.pages.push({path:route.path,status:response.status(),staticContent:true,title:route.title,descriptionLength:route.description.length,canonical:siteUrl+route.path})
  }
  assert.equal(titleSet.size,routes.length);assert.equal(descriptionSet.size,routes.length)
  await page.goto(base+'/',{waitUntil:'networkidle'})
  assert.equal(await page.locator('[data-sc-cue]').first().evaluate(el=>getComputedStyle(el).opacity),'1')
  assert.equal(await page.locator('.home-service').first().evaluate(el=>getComputedStyle(el).opacity),'1')
  await page.screenshot({path:`${out}/homepage-no-js.png`})
  await page.setViewportSize({width:390,height:844})
  assert.equal(await page.locator('#main-nav').evaluate(el=>getComputedStyle(el).display),'flex')
  await page.goto(base+'/contact',{waitUntil:'networkidle'})
  assert.equal(await page.locator('form').getAttribute('method'),'post')
  assert((await page.locator('form').getAttribute('action')).startsWith('https://formspree.io/'))
  const missing = await page.goto(base+'/this-page-does-not-exist',{waitUntil:'networkidle'})
  assert.equal(missing.status(),404)
  assert((await page.locator('meta[name="robots"]').getAttribute('content')).includes('noindex'))
  assert.equal(await page.locator('link[rel="canonical"]').count(),0)
  report.checks.push('All public raw HTML pages, no-JS content/navigation, valid internal links, sitemap/canonical agreement, and true 404 passed')
  const htmlRedirect = await fetch(base+'/services.html',{redirect:'manual'})
  assert.equal(htmlRedirect.status,308)
  assert.equal(htmlRedirect.headers.get('location'),'/services')
  const slashRedirect = await fetch(base+'/services/',{redirect:'manual'})
  assert.equal(slashRedirect.status,308)
  assert.equal(slashRedirect.headers.get('location'),'/services')
  for (const asset of ['/brand/social-card.png','/brand/mg-mark.svg','/brand/logo-720.webp','/robots.txt','/sitemap.xml']) assert.equal((await fetch(base+asset)).status,200,asset)
  report.checks.push('Local static preview clean URL redirects and referenced assets passed (not a production hosting test)')
  const js = await browser.newContext({viewport:{width:1440,height:900}})
  await js.addInitScript(()=>{Element.prototype.requestPointerLock=()=>Promise.reject();Element.prototype.setPointerCapture=()=>{};Element.prototype.releasePointerCapture=()=>{}})
  const live = await js.newPage()
  live.on('pageerror',error=>report.hydrationErrors.push(live.url() + ' ' + error.stack))
  live.on('console',message=>{if(message.type()==='error'&&/hydration|Minified React|did not match/i.test(message.text()))report.hydrationErrors.push(message.text())})
  for (const route of routes) {
    await live.goto(base+route.path,{waitUntil:'networkidle'})
    assert.equal(await live.title(),route.title)
    assert.equal(await live.locator('link[rel="canonical"]').count(),1)
  }
  await live.goto(base+'/',{waitUntil:'networkidle'})
  await live.waitForFunction(()=>window.ScrollCraft?.instances.length===1)
  await live.screenshot({path:`${out}/homepage-hydrated.png`})
  await live.getByRole('navigation',{name:'Main navigation'}).getByRole('link',{name:'Expertise'}).click()
  await live.waitForURL('**/services')
  await live.waitForFunction(title=>document.title===title,getSeo('/services').title)
  assert.equal(await live.title(),getSeo('/services').title)
  assert.equal(await live.locator('meta[name="description"]').getAttribute('content'),getSeo('/services').description)
  assert.equal(await live.locator('link[rel="canonical"]').getAttribute('href'),siteUrl+'/services')
  await live.getByRole('link',{name:'Travel agency systems',exact:false}).first().click()
  await live.waitForURL('**/services/tam-system-development')
  await live.waitForFunction(title=>document.title===title,getSeo('/services/tam-system-development').title)
  assert.equal(await live.title(),getSeo('/services/tam-system-development').title)
  const crumbs=JSON.parse(await live.locator('#seo-structured-data').textContent())['@graph'].find(node=>node['@type']==='BreadcrumbList')
  assert.deepEqual(crumbs.itemListElement.map(item=>item.name),['Home','Services','Travel Agency Management'])
  assert.equal(await live.locator('title').count(),1)
  report.navigation.push('Client navigation updates titles, descriptions, canonicals and service breadcrumb without duplicates')
  await live.setViewportSize({width:390,height:844})
  await live.goto(base+'/contact',{waitUntil:'networkidle'})
  await live.screenshot({path:`${out}/contact-mobile.png`,fullPage:true})
  assert.equal(await live.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
  await live.route('https://formspree.io/**',route=>route.fulfill({status:200,contentType:'application/json',body:'{"ok":true}'}))
  await live.getByLabel('Your name').fill('SEO QA');await live.getByLabel('Email address').fill('seo@example.com');await live.getByLabel('WhatsApp number').fill('+923000000000');await live.getByLabel('What can we help with?').selectOption('SaaS MVP');await live.getByLabel('A little about your project').fill('Local mocked SEO regression test.');await live.getByRole('button',{name:'Send project request'}).click();await live.getByText('Message received.').waitFor()
  report.checks.push('Hydrated mobile contact form passes with mocked response; no external inquiry sent')
  assert.equal(report.hydrationErrors.length,0,JSON.stringify(report.hydrationErrors))
  console.log(JSON.stringify(report,null,2))
} finally {fs.writeFileSync(`${out}/report.json`,JSON.stringify(report,null,2));await browser.close()}

